const gradientFor = (artist: string) => {
  const key = artist.split(", ")[0];
  let h = 0;
  for (const c of key) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return GRADIENTS[h % GRADIENTS.length];
};

